export function accepted() {
  const l = state.settings.legal || {};
  return l.acceptedVersion === TERMS_VERSION;
}

export function acceptedAt() {
  const l = state.settings.legal || {};
  return l.acceptedAt || null;
}

export function accept() {
  state.settings.legal = {
    acceptedVersion: TERMS_VERSION,
    acceptedAt: Date.now(),
    acceptedBuild: state.settings._build || ''
  };
  save();
}

/** למקרה שהמשתמש רוצה לבטל את הסכמתו */
export function revoke() {
  state.settings.legal = { acceptedVersion: '', acceptedAt: null };
  save();
}
